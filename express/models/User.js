import mongoose from "mongoose";

const userSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: [true, "Name is required"],
      trim: true,
    },
    email: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
      trim: true,
    },
    number: {
      type: String,
      match: [/^\d{10}$/, "Invalid phone number"],
    },
  },
  { timestamps: true }
);

export default mongoose.model("User", userSchema);